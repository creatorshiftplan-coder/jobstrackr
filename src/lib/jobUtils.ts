// Check if last_date_display contains TBD-like values
export const isTBDDateDisplay = (displayValue: string | null): boolean => {
    if (!displayValue) return false;
    const tbdPatterns = ['tbd', 'to be announced', 'walk in', 'walk-in', 'walkin', 'n/a', 'not available'];
    const lowerValue = displayValue.toLowerCase().trim();
    return tbdPatterns.some(pattern => lowerValue.includes(pattern));
};

// Infer category from department/title using keyword matching
export const inferCategory = (department: string, title: string): string => {
    const text = `${department} ${title}`.toLowerCase();

    for (const [category, keywords] of Object.entries(CATEGORY_KEYWORDS)) {
        if (keywords.some(keyword => text.includes(keyword))) {
            return category;
        }
    }

    return "Govt";
};

export const matchesSectorPreference = (department: string, title: string, sector: string): boolean => {
    const text = `${department} ${title}`.toLowerCase();
    const normalizedSector = sector.toLowerCase();
    const inferredCategory = inferCategory(department, title).toLowerCase();

    if (
        inferredCategory === normalizedSector ||
        inferredCategory.includes(normalizedSector) ||
        normalizedSector.includes(inferredCategory)
    ) {
        return true;
    }

    const keywords = CATEGORY_KEYWORDS[sector] || [];
    if (keywords.some(keyword => text.includes(keyword))) {
        return true;
    }

    return text.includes(normalizedSector);
};

export const parseJobDeadline = (lastDate: string | null | undefined): Date | null => {
    if (!lastDate) return null;

    // Strip newlines and time-related text for matching
    let cleaned = lastDate.replace(/\n/g, " ").trim();
    cleaned = cleaned
        .replace(/\(?\s*\d{1,2}:\d{2}\s*(?:AM|PM|am|pm)?\s*\)?/g, "")
        .replace(/from\s+\d{1,2}:\d{2}\s*(?:AM|PM|am|pm)?\s*onwards?/gi, "")
        .trim();
    if (!cleaned) cleaned = lastDate.replace(/\n/g, " ").trim();

    // YYYY-MM-DD
    if (/^\d{4}-\d{2}-\d{2}$/.test(cleaned)) {
        const [year, month, day] = cleaned.split("-").map(Number);
        return new Date(year, month - 1, day, 23, 59, 59, 999);
    }

    // DD/MM/YYYY, DD-MM-YYYY or DD.MM.YYYY (dot is the dominant Indian format,
    // e.g. "31.07.2026" — native Date() can't parse it, so match it explicitly).
    const dmy = cleaned.match(/^(\d{1,2})[\/\-.](\d{1,2})[\/\-.](\d{4})$/);
    if (dmy) {
        return new Date(Number(dmy[3]), Number(dmy[2]) - 1, Number(dmy[1]), 23, 59, 59, 999);
    }

    // DD-MM YYYY (space-separated year)
    const dmySpace = cleaned.match(/^(\d{1,2})[\/\-.](\d{1,2})\s+(\d{4})$/);
    if (dmySpace) {
        return new Date(Number(dmySpace[3]), Number(dmySpace[2]) - 1, Number(dmySpace[1]), 23, 59, 59, 999);
    }

    // DD Month YYYY
    const monthMap: Record<string, number> = {
        jan: 0, feb: 1, mar: 2, apr: 3, may: 4, jun: 5,
        jul: 6, aug: 7, sep: 8, oct: 9, nov: 10, dec: 11,
    };
    const named = cleaned.match(/^(\d{1,2})[\s\-/]([a-zA-Z]+)[\s\-/](\d{4})$/);
    if (named) {
        const mon = monthMap[named[2].toLowerCase().slice(0, 3)];
        if (mon !== undefined) {
            return new Date(Number(named[3]), mon, Number(named[1]), 23, 59, 59, 999);
        }
    }

    // Robust fallback: pull the first recognizable date out of any leftover prose
    // that the exact-match branches above rejected — e.g. "08.07.2026, up to 5:15 PM"
    // or "10.07.2026 (09:00 AM to 10:00 AM)". Without this such rows parse to null
    // and are wrongly treated as never-expiring.
    const isoAnywhere = cleaned.match(/(\d{4})-(\d{1,2})-(\d{1,2})/);
    if (isoAnywhere) {
        return new Date(Number(isoAnywhere[1]), Number(isoAnywhere[2]) - 1, Number(isoAnywhere[3]), 23, 59, 59, 999);
    }
    const dmyAnywhere = cleaned.match(/(\d{1,2})[\/\-.](\d{1,2})[\/\-.](\d{4})/);
    if (dmyAnywhere) {
        return new Date(Number(dmyAnywhere[3]), Number(dmyAnywhere[2]) - 1, Number(dmyAnywhere[1]), 23, 59, 59, 999);
    }
    // "DDth Month YYYY" with an ordinal suffix and/or a leading weekday/prose,
    // e.g. "24th July 2026", "Friday, 10th July 2026 (09:00 AM…)". The month name
    // guard keeps this from matching non-date phrases like "45 days … 2026".
    const namedAnywhere = cleaned.match(/(\d{1,2})(?:st|nd|rd|th)?\s+([A-Za-z]{3,})\s+(\d{4})/i);
    if (namedAnywhere) {
        const mon = monthMap[namedAnywhere[2].toLowerCase().slice(0, 3)];
        if (mon !== undefined) {
            return new Date(Number(namedAnywhere[3]), mon, Number(namedAnywhere[1]), 23, 59, 59, 999);
        }
    }

    // Fallback: native Date parse
    const parsed = new Date(cleaned);
    return Number.isNaN(parsed.getTime()) ? null : parsed;
};

export const isJobActive = (lastDate: string | null | undefined): boolean => {
    const deadline = parseJobDeadline(lastDate);
    if (!deadline) return true;
    return deadline.getTime() >= Date.now();
};

interface JobDeadlineFields {
    last_date: string | null;
    last_date_display?: string | null;
    created_at?: string | null;
}

// Older ingestion paths stored `today + 1 year` in last_date when the scraped
// deadline was missing or unparseable, so a large batch of rows carries a fake
// deadline exactly one year after created_at (and no raw display text backing
// it). Those rows pass isJobActive for a full year after the posting died.
const FABRICATED_GAP_MIN_DAYS = 358;
const FABRICATED_GAP_MAX_DAYS = 373;

const looksFabricatedDeadline = (job: JobDeadlineFields, deadline: Date): boolean => {
    if (!job.created_at) return false;
    // A raw scraped string that parses to the same day vouches for the date.
    if (job.last_date_display) {
        const displayDate = parseJobDeadline(job.last_date_display);
        if (displayDate && Math.abs(displayDate.getTime() - deadline.getTime()) < 48 * 60 * 60 * 1000) {
            return false;
        }
    }
    const created = new Date(job.created_at);
    if (Number.isNaN(created.getTime())) return false;
    const gapDays = (deadline.getTime() - created.getTime()) / (24 * 60 * 60 * 1000);
    return gapDays >= FABRICATED_GAP_MIN_DAYS && gapDays <= FABRICATED_GAP_MAX_DAYS;
};

// Deadline we can actually trust: the stored last_date unless it looks
// fabricated, in which case fall back to the raw scraped text (the frontend
// parser handles formats the ingestion parser missed), else null (unknown).
export const getTrustedJobDeadline = (job: JobDeadlineFields): Date | null => {
    const stored = parseJobDeadline(job.last_date);
    if (!stored) return null;
    if (!looksFabricatedDeadline(job, stored)) return stored;
    return job.last_date_display ? parseJobDeadline(job.last_date_display) : null;
};

// How long a job with no trustworthy deadline (TBD, walk-in, unparseable, or
// fabricated) stays in recommendation feeds before it's presumed closed.
export const UNKNOWN_DEADLINE_GRACE_DAYS = 60;

// Feed-facing activity check. Unlike isJobActive (which keeps unknown-deadline
// jobs forever), unknown-deadline jobs age out after a grace period so stale
// postings — including rows with fabricated year-out deadlines — stop
// surfacing as recommendations.
export const isJobOpenForFeed = (job: JobDeadlineFields): boolean => {
    const deadline = getTrustedJobDeadline(job);
    if (deadline) return deadline.getTime() >= Date.now();
    if (!job.created_at) return true;
    const created = new Date(job.created_at);
    if (Number.isNaN(created.getTime())) return true;
    return Date.now() - created.getTime() <= UNKNOWN_DEADLINE_GRACE_DAYS * 24 * 60 * 60 * 1000;
};

// Shorten qualification for display
export const shortenQualification = (qualification: string): string => {
    if (!qualification) return "Any";

    const text = qualification.toLowerCase();

    // Order matters - check more specific patterns first
    if (text.includes("phd") || text.includes("doctorate")) {
        return "PhD";
    }
    if (text.includes("post") || text.includes("master") || text.includes("m.tech") || text.includes("mba") || text.includes("m.sc")) {
        return "Post Graduate";
    }
    if (text.includes("b.tech") || text.includes("b.e") || text.includes("engineering")) {
        return "B.Tech/B.E";
    }
    if (text.includes("graduate") || text.includes("graduation") || text.includes("bachelor") || text.includes("degree") || text.includes("b.sc") || text.includes("b.a") || text.includes("b.com")) {
        return "Graduate";
    }
    if (text.includes("diploma")) {
        return "Diploma";
    }
    if (text.includes("iti")) {
        return "ITI";
    }
    // Check 12th before 10th to avoid false matches
    if (text.includes("12th") || text.includes("class xii") || text.includes("intermediate") || text.includes("higher secondary") || text.includes("+2")) {
        return "12th Pass";
    }
    if (text.includes("10th") || text.includes("class x ") || text.includes("class x,") || text.includes("matriculation") || text.includes("ssc pass") || text.includes("10 pass")) {
        return "10th Pass";
    }
    if (text.includes("8th") || text.includes("class viii") || text.includes("middle")) {
        return "8th Pass";
    }

    // Return first 15 chars if no match
    return qualification.length > 15 ? qualification.slice(0, 15) + "..." : qualification;
};

// Format age limit for consistent display across cards and details
export const formatAgeLimit = (
    ageMin?: number | null,
    ageMax?: number | null,
    unit: string = "years"
): string => {
    const min = typeof ageMin === "number" && Number.isFinite(ageMin) ? ageMin : null;
    const max = typeof ageMax === "number" && Number.isFinite(ageMax) ? ageMax : null;

    // Treat very small ages as invalid placeholders (e.g., 1) and hide them.
    let normalizedMin = min !== null && min >= 10 ? min : null;
    let normalizedMax = max !== null && max >= 10 ? max : null;

    if (normalizedMin !== null && normalizedMax !== null && normalizedMin > normalizedMax) {
        const tmp = normalizedMin;
        normalizedMin = normalizedMax;
        normalizedMax = tmp;
    }

    if (normalizedMin !== null && normalizedMax !== null) return `${normalizedMin} - ${normalizedMax} ${unit}`;
    if (normalizedMin !== null) return `From ${normalizedMin} ${unit}`;
    if (normalizedMax !== null) return `Upto ${normalizedMax} ${unit}`;
    return "Not Available";
};

// Extract the total vacancy count from the "Total" row of a vacancies_detail breakdown table.
const extractVacancyBreakdownTotal = (
    vacanciesDetail?: Record<string, string>[] | null
): string => {
    if (!Array.isArray(vacanciesDetail)) return "";
    for (const row of vacanciesDetail) {
        const vals = Object.values(row).map((v: any) => String(v).toLowerCase().trim());
        const isTotalRow = vals.some((v: string) => v === "total" || v === "grand total");
        if (!isTotalRow) continue;
        const num = Object.values(row).find((v: any) => {
            const s = String(v).trim().replace(/,/g, "");
            return s !== "" && !isNaN(Number(s));
        });
        if (num) return String(num).trim().replace(/,/g, "");
    }
    return "";
};

// Single source of truth for the vacancy summary shown on cards and the details page.
// Prioritizes the total from the breakdown table over unhelpful display placeholders.
export const getVacancyDisplay = (
    job: {
        vacancies_display?: string | null;
        vacancies?: number | null;
        job_metadata?: { vacancies_detail?: Record<string, string>[] } | null;
    },
    word: string = "Posts"
): string => {
    const breakdownTotal = extractVacancyBreakdownTotal(job.job_metadata?.vacancies_detail);
    if (breakdownTotal) return `${breakdownTotal} ${word}`;

    const display = job.vacancies_display?.trim();
    const displayLower = display?.toLowerCase();
    if (display && displayLower !== "not found" && displayLower !== "tbd" && displayLower !== "n/a") {
        return display;
    }

    if (job.vacancies) return `${job.vacancies} ${word}`;
    return "TBD";
};
